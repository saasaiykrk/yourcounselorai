/// The country of a stored number (+919876543210 → India), by its longest matching calling code.
/// Shared codes (+1, +7) pick the most likely country: the United States, Russia.
({Country country, String national})? splitMobile(String? e164) {
  if (e164 == null || !e164.startsWith('+')) return null;
  final digits = e164.substring(1);
  const preferred = {'1': 'US', '7': 'RU'};
  for (var len = 3; len >= 1; len--) {
    if (digits.length <= len) continue;
    final code = digits.substring(0, len);
    final matches = kCountries.where((c) => c.dial == code).toList();
    if (matches.isEmpty) continue;
    final pick = matches.firstWhere((c) => c.iso == preferred[code], orElse: () => matches.first);
    return (country: pick, national: digits.substring(len));
  }
  return null;
}
